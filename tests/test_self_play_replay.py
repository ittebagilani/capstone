"""100-game replay (Itteba Phase 1, Aug 22-24): infer_move must recover every move of many
full games purely from before/after occupancy, with zero access to the move itself.

No offline PGN corpus is available in this environment, so games are generated by random
self-play instead of downloaded. Over 100 games this still exercises captures, castling,
en passant, promotion, and checkmate — real PGN games remain worth swapping in later
(CLAUDE.md §7.5 makes the same call for vision dataset collection, for the same reason).
"""
import random

import chess

from backend.inference import board_to_squares, infer_move

GAMES = 100
SEED = 0
MAX_PLIES = 200


def play_random_game(rng: random.Random) -> chess.Board:
    board = chess.Board()
    for _ in range(MAX_PLIES):
        if board.is_game_over():
            break
        move = rng.choice(list(board.legal_moves))
        board.push(move)
    return board


def test_self_play_games_reconstruct_every_move():
    rng = random.Random(SEED)
    total_moves = 0

    for _ in range(GAMES):
        game = play_random_game(rng)
        replay = chess.Board()
        for move in game.move_stack:
            prev = board_to_squares(replay)
            replay.push(move)
            observed = board_to_squares(replay)
            replay.pop()

            result, status = infer_move(prev, observed, replay)
            assert status in ("ok", "promotion_ambiguous"), (replay.fen(), move, status)
            if status == "ok":
                assert result == move
            else:
                assert move in result

            replay.push(move)
            total_moves += 1

    assert total_moves > 0
